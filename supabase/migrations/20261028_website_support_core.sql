-- SHO WEB SUPPORT production data model
-- Apply to the existing Supabase project before switching the website from demo mode.

create table if not exists public.website_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.website_settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.website_sites (
  site_id text primary key,
  site_name text not null default '',
  status text not null default 'request_waiting'
    check (status in ('request_waiting','building','sho_review','customer_review','live','private','improving_private')),
  current_note text not null default '',
  customer_approved boolean not null default false,
  preview_url text,
  public_url text,
  repo_full_name text,
  publish_branch text not null default 'main',
  live_path text not null default '/' check (live_path in ('/','/docs')),
  offline_path text not null default '/docs' check (offline_path in ('/','/docs')),
  custom_domain text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.website_site_users (
  site_id text not null references public.website_sites(site_id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'editor' check (role in ('owner','editor','viewer')),
  created_at timestamptz not null default now(),
  primary key (site_id,user_id)
);

create table if not exists public.website_intakes (
  site_id text primary key references public.website_sites(site_id) on delete cascade,
  payload jsonb not null default '{}'::jsonb,
  last_saved_at timestamptz,
  submitted_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists public.website_profiles (
  site_id text primary key references public.website_sites(site_id) on delete cascade,
  industry text,
  summary text,
  preferences jsonb not null default '{}'::jsonb,
  decisions jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.website_line_links (
  site_id text primary key references public.website_sites(site_id) on delete cascade,
  line_user_id text unique not null,
  line_display_name text,
  linked_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.website_jobs (
  id bigint generated by default as identity primary key,
  site_id text not null references public.website_sites(site_id) on delete cascade,
  kind text not null check (kind in ('initial_create','customer_revision','sho_revision','improvement')),
  status text not null default 'queued' check (status in ('queued','running','sho_review','done','error')),
  instruction text,
  payload jsonb,
  error_message text,
  created_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz
);

create table if not exists public.website_activity (
  id bigint generated by default as identity primary key,
  site_id text not null references public.website_sites(site_id) on delete cascade,
  actor_type text not null default 'system',
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  detail text,
  payload jsonb,
  created_at timestamptz not null default now()
);

create index if not exists website_sites_status_idx on public.website_sites(status);
create index if not exists website_jobs_status_created_idx on public.website_jobs(status,created_at);
create index if not exists website_jobs_site_created_idx on public.website_jobs(site_id,created_at desc);
create index if not exists website_activity_site_created_idx on public.website_activity(site_id,created_at desc);
create index if not exists website_site_users_user_idx on public.website_site_users(user_id);

create or replace function public.website_touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists website_sites_touch on public.website_sites;
create trigger website_sites_touch before update on public.website_sites
for each row execute function public.website_touch_updated_at();

drop trigger if exists website_intakes_touch on public.website_intakes;
create trigger website_intakes_touch before update on public.website_intakes
for each row execute function public.website_touch_updated_at();

drop trigger if exists website_profiles_touch on public.website_profiles;
create trigger website_profiles_touch before update on public.website_profiles
for each row execute function public.website_touch_updated_at();

drop trigger if exists website_line_links_touch on public.website_line_links;
create trigger website_line_links_touch before update on public.website_line_links
for each row execute function public.website_touch_updated_at();

create or replace function public.is_website_admin()
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select exists(select 1 from public.website_admins where user_id = auth.uid());
$$;

create or replace function public.has_website_site_access(target_site_id text)
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select public.is_website_admin()
     or exists(
       select 1 from public.website_site_users
       where site_id = target_site_id and user_id = auth.uid()
     );
$$;

