insert into storage.buckets (id,name,public)
values ('website-intake-files','website-intake-files',false)
on conflict (id) do update set public=false;

drop policy if exists website_files_select on storage.objects;
create policy website_files_select on storage.objects
for select to authenticated
using (
  bucket_id='website-intake-files'
  and public.has_website_site_access((storage.foldername(name))[1])
);

drop policy if exists website_files_insert on storage.objects;
create policy website_files_insert on storage.objects
for insert to authenticated
with check (
  bucket_id='website-intake-files'
  and public.has_website_site_access((storage.foldername(name))[1])
);

drop policy if exists website_files_update on storage.objects;
create policy website_files_update on storage.objects
for update to authenticated
using (
  bucket_id='website-intake-files'
  and public.has_website_site_access((storage.foldername(name))[1])
)
with check (
  bucket_id='website-intake-files'
  and public.has_website_site_access((storage.foldername(name))[1])
);

drop policy if exists website_files_delete on storage.objects;
create policy website_files_delete on storage.objects
for delete to authenticated
using (
  bucket_id='website-intake-files'
  and public.has_website_site_access((storage.foldername(name))[1])
);
