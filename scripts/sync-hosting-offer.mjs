import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const source=name=>fileURLToPath(new URL('../'+name,import.meta.url));
import {HOSTING_OFFER} from '../supabase/functions/_shared/hosting-offer.mjs';
const yen=HOSTING_OFFER.renewal_fee_jpy.toLocaleString('ja-JP');
const card=`<!-- HOSTING_OFFER_START -->
<section class="hosting-fee" data-hosting-offer="${HOSTING_OFFER.version}" aria-label="サイト公開維持費">
<h2>サイト公開維持費</h2><p>公開日から最初の12か月は<strong>制作料金に含みます。</strong></p>
<p class="hosting-fee-price">2年目以降 <strong>${yen}円／年（税込・年払い）</strong><small>月換算500円。月払いではありません。</small></p>
<p>SHO管理で公開を継続する場合の料金です。満了30日前までにご案内し、継続のお申込みと入金で12か月更新します。<strong>自動更新・自動課金はありません。</strong></p>
<p>公開環境・HTTPS・公開版の保管・障害時の復旧対応が対象です。写真や文章などの内容更新、大幅な変更、お客様名義ドメインの取得・更新実費は別料金です。終了・引き渡し条件は<a href="website-terms.html">利用条件</a>をご確認ください。</p>
</section>
<!-- HOSTING_OFFER_END -->`;
const targets=['website-support.html','website-create.html','band-homepage.html','website-order.html','website-order-confirm.html','website-faq.html','website-legal.html','website-terms.html','website-payment.html'];
const verify=process.argv.includes('--check');let failed=false;
for(const name of targets){let html=readFileSync(source(name),'utf8'),next;
 if(html.includes('<!-- HOSTING_OFFER_START -->'))next=html.replace(/<!-- HOSTING_OFFER_START -->[\s\S]*?<!-- HOSTING_OFFER_END -->/,card);
 else if(name==='website-order-confirm.html')next=html.replace('<div class="actions">',card+'\n<div class="actions">');
 else if(name==='website-support.html')next=html.replace('<section class="section"><div class="container">',card+'\n<section class="section"><div class="container">');
 else if(name==='website-order.html')next=html.replace('<section class="section">',card+'\n<section class="section">');
 else next=html.replace('</main>',card+'\n</main>');
 if(next===html&&!html.includes('<!-- HOSTING_OFFER_START -->'))throw Error('No insertion target: '+name);
 if(verify){if(next!==html){console.error('Stale hosting price: '+name);failed=true;}}else writeFileSync(source(name),next);
}
const js='// Generated by scripts/sync-hosting-offer.mjs. Public prices only.\nwindow.SHO_HOSTING_OFFER=Object.freeze('+JSON.stringify(HOSTING_OFFER)+');\n';
if(verify){if(readFileSync(source('website-hosting-offer.js'),'utf8')!==js)failed=true;}else writeFileSync(source('website-hosting-offer.js'),js);
if(failed)process.exitCode=1;else console.log('Hosting offer synchronized across nine sales pages.');
